/**
 * One example formula for every Excel function Petak supports (Phase 4).
 *
 * The formulas use the data block DATA (sheet "S", columns A–V). The reference result comes from
 * LibreOffice (tests/functions/libreoffice.mjs writes libreoffice-results.json). Where LibreOffice
 * 24.2 does not have the function (Excel 365's newer functions) the example gives `ms`: the value
 * Excel returns, worked out by hand on purpose-simple arguments (or taken from Microsoft's
 * documentation example). Array results are reduced to one value (INDEX / SUM / TEXTJOIN-free
 * reducers) so one cell compares the whole result. Volatile functions are checked by range.
 */

// ---- the data block: rows 1–12, columns A–V
const x = [2, 4, 4, 4, 5, 5, 7, 9, 10, 12];
const y = [3, 5, 6, 8, 9, 11, 14, 15, 18, 20];
const text = ['apple', 'banana', 'cherry', 'apple', 'date', 'fig', 'grape', 'apple', 'kiwi', 'lemon'];
const dates = [45306, 45337, 45366, 45397, 45427, 45458, 45488, 45519, 45550, 45580]; // 2024-01-15, then the 15th / 16th of each month
const flows = [-10000, 2750, 4250, 3250, 2750];
const mixed = [true, 'x', 3, null, 'y', 0, false, 7, 'z', null];
const db = [
  ['Tree', 'Height', 'Age', 'Yield'],
  ['Apple', 18, 20, 14],
  ['Pear', 12, 12, 10],
  ['Cherry', 13, 14, 9],
  ['Apple', 14, 15, 10],
  ['Pear', 9, 8, 8],
];
const xirrDates = [39448, 39508, 39751, 39859, 39904]; // 2008-01-01, 03-01, 10-30, 2009-02-15, 04-01

/** rows of the data block, A..V (null = empty) */
export const DATA = Array.from({ length: 12 }, (_, r) => {
  const row = new Array(22).fill(null);
  if (r < 10) {
    row[0] = x[r];
    row[1] = y[r];
    row[2] = text[r];
    row[3] = dates[r];
    row[6] = mixed[r];
  }
  if (r < 5) row[4] = flows[r];
  if (r < 3) row[5] = [3, 6, 9][r]; // F: bins
  if (r < 6) db[r].forEach((v, i) => (row[7 + i] = v)); // H:K database
  if (r < 2) {
    row[12] = ['Tree', 'Apple'][r]; // M: criteria
    row[13] = ['Height', '>10'][r]; // N: criteria
    row[14] = ['Tree', 'Cherry'][r]; // O: criteria matching one record
    row[15] = [[1, 2], [3, 4]][r][0]; // P:Q matrix
    row[16] = [[1, 2], [3, 4]][r][1];
    row[17] = [[5, 6], [7, 8]][r][0]; // R:S matrix
    row[18] = [[5, 6], [7, 8]][r][1];
  }
  if (r >= 3 && r < 6) [[2, 1, 1], [1, 3, 2], [1, 0, 0]][r - 3].forEach((v, i) => (row[15 + i] = v)); // P4:R6
  if (r < 5) {
    row[19] = flows[r]; // T: XIRR values
    row[20] = xirrDates[r]; // U: XIRR dates
  }
  if (r === 0) row[21] = '=A1*2'; // V1: a formula (ISFORMULA, FORMULATEXT)
  if (r === 10) row[0] = 'Total'; // A11: text below the numbers
  return row;
});

