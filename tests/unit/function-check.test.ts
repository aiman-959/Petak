/**
 * Phase 4: every supported Excel function, computed by Petak, against LibreOffice (and against
 * Excel's documented result where LibreOffice 24.2 does not have the function).
 *   node tests/functions/libreoffice.mjs                         refresh the LibreOffice results
 *   UPDATE_DOCS=1 npx vitest run tests/unit/function-check.test.ts  rewrite FUNCTION-CHECK.md
 */
import { expect, it } from 'vitest';
import fs from 'node:fs';
import { FormulaEngine } from '../../src/engine/formulaCore';
// @ts-expect-error plain JS data module
import { DATA, EXAMPLES } from '../functions/examples.mjs';

type Ref = { t: 'n' | 's' | 'b' | 'e' | 'z'; v?: unknown };
const lo = JSON.parse(fs.readFileSync(new URL('../functions/libreoffice-results.json', import.meta.url), 'utf8')) as { version: string; results: Record<string, Ref> };

/**
 * Where LibreOffice differs from Excel. Petak must give the Excel result listed here,
 * so these are still checked, just against Excel instead of LibreOffice.
 */
const KNOWN: Record<string, [excel: unknown, why: string]> = {
  BESSELJ: [0.329925829, "Excel's documented result; LibreOffice computes a value 1e-7 closer to the exact Bessel function"],
  DURATION: [5.993775, "Excel's documented example; LibreOffice gives a slightly different duration for basis 1 (actual/actual)"],
  MDURATION: [5.73567, "Excel's documented example; same basis-1 difference as DURATION"],
  EXPAND: [6, 'LibreOffice 24.2 has no EXPAND (it reads it as one error value); Excel pads to 3×2, so COUNTA is 6'],
  FILTER: [38, 'LibreOffice 24.2 has no FILTER; Excel sums 7+9+10+12'],
  COUNT: [3, 'Excel does not count TRUE/FALSE held in cells (only 3, 0 and 7 here); LibreOffice stores booleans as numbers and counts them'],
  'PERCENTRANK.INC': [0.666, 'Excel cuts the result to 3 digits (6/9 → 0.666); LibreOffice rounds (0.667)'],
};

const COL = 23;
function petakResults(): Map<string, unknown> {
  const e = new FormulaEngine();
  e.addSheet('s1', 'S');
  e.suspend();
  const rows: unknown[][] = [];
  const n = Math.max(DATA.length, EXAMPLES.length);
  for (let r = 0; r < n; r++) {
    const row = r < DATA.length ? [...DATA[r]] : new Array(22).fill(null);
    while (row.length < COL) row.push(null);
    row[COL] = r < EXAMPLES.length ? EXAMPLES[r][1] : null;
    rows.push(row);
  }
  e.loadRows('s1', 0, rows as never);
  const out = new Map<string, unknown>();
  for (const s of e.resumeAll()) for (const c of s.cells) if (c.c === COL) out.set(EXAMPLES[c.r][0], c.v);
  return out;
}

const same = (a: unknown, b: unknown): boolean => {
  if (typeof a === 'number' && typeof b === 'number') return Math.abs(a - b) <= 1e-9 + 1e-7 * Math.abs(b);
  if (typeof a === 'boolean' || typeof b === 'boolean') return (a === true || a === 1) === (b === true || b === 1) && (typeof a === 'boolean' || typeof a === 'number');
  return String(a) === String(b);
};

it('every supported function gives the reference result', () => {
  const got = petakResults();
  const rows: Row[] = [];
  for (const [fn, formula, ms] of EXAMPLES as Array<[string, string, unknown?]>) {
    const p = got.get(fn);
    const r = lo.results[fn];
    const loMissing = !r || (r.t === 'e' && r.v === '#NAME?');
    let ref: unknown;
    let source: string;
    if (ms !== undefined && (loMissing || typeof ms === 'boolean')) {
      ref = ms;
      source = typeof ms === 'boolean' ? 'range check' : 'Excel (documented / worked by hand)';
    } else {
      ref = r?.t === 'z' ? '' : r?.v;
      source = 'LibreOffice';
    }
    const ok = same(p, ref);
    const known = KNOWN[fn];
    rows.push({ fn, formula, petak: p, ref, source, ok, note: known && same(p, known[0]) ? known[1] : undefined, excel: known?.[0] });
  }
  const bad = rows.filter((x) => !x.ok && !x.note);
  // every explanation must still be needed
  expect(Object.keys(KNOWN).filter((k) => rows.find((r) => r.fn === k)?.ok)).toEqual([]);
  if (process.env.UPDATE_DOCS) writeReport(rows);
  expect(bad.map((b) => `${b.fn}: ${b.formula} → Petak ${JSON.stringify(b.petak)}, ${b.source} ${JSON.stringify(b.ref)}`)).toEqual([]);
  expect(rows.length).toBeGreaterThan(470);
});

type Row = { fn: string; formula: string; petak: unknown; ref: unknown; source: string; ok: boolean; note?: string; excel?: unknown };

function writeReport(rows: Row[]) {
  const by = (s: string) => rows.filter((r) => r.ok && r.source === s).length;
  const fmt = (v: unknown) => (typeof v === 'number' ? String(+v.toPrecision(12)) : JSON.stringify(v)).replace(/\|/g, '\\|');
  const lines = [
    '# Function check',
    '',
    `Every Excel function Petak supports (${rows.length}), one example each, computed by Petak and compared with a reference.`,
    `Generated by \`tests/unit/function-check.test.ts\` (examples in \`tests/functions/examples.mjs\`, reference from ${lo.version}).`,
    '',
    '| Result | Functions |',
    '|---|---:|',
    `| Same as LibreOffice | ${by('LibreOffice')} |`,
    `| Same as Excel's documented / hand-worked result (LibreOffice 24.2 lacks the function) | ${by('Excel (documented / worked by hand)')} |`,
    `| Volatile (NOW, TODAY, RAND…): result in the expected range | ${by('range check')} |`,
    `| Differs from LibreOffice, same as Excel (explained below) | ${rows.filter((r) => !r.ok && r.note).length} |`,
    `| Wrong | ${rows.filter((r) => !r.ok && !r.note).length} |`,
    '',
    'Numbers match when they agree to 7 significant digits.',
    '',
  ];
  const diff = rows.filter((r) => !r.ok);
  if (diff.length) {
    lines.push('## Where LibreOffice differs from Excel', '', '| Function | Formula | Petak | Excel | LibreOffice | Why |', '|---|---|---|---|---|---|');
    for (const r of diff) lines.push(`| ${r.fn} | \`${r.formula.replace(/\|/g, '\\|')}\` | ${fmt(r.petak)} | ${r.excel === undefined ? '?' : fmt(r.excel)} | ${fmt(r.ref)} | ${r.note ?? '**not explained**'} |`);
    lines.push('');
  }
  lines.push('## All functions', '', '| Function | Formula | Petak | Reference |', '|---|---|---|---|');
  for (const r of rows) lines.push(`| ${r.fn} | \`${r.formula.replace(/\|/g, '\\|')}\` | ${fmt(r.petak)} | ${r.ok ? '✓' : r.note ? '≈' : '✗'} ${fmt(r.ref)} (${r.source === 'LibreOffice' ? 'LO' : r.source === 'range check' ? 'range' : 'Excel'}) |`);
  fs.writeFileSync(new URL('../../FUNCTION-CHECK.md', import.meta.url), lines.join('\n') + '\n');
}
